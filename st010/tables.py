"""How much the world shrinks on each of the raster lines a screen is built from."""


def sine(angle):
    """The sine of an angle, by the top byte of it."""
    return SINE[(angle >> 8) & 0xFF]


def cosine(angle):
    """The cosine of the same angle, which is the sine a quarter turn along."""
    return SINE[((angle + QUADRANT) >> 8) & 0xFF]


def arctangent(across, down):
    """The angle of a point, from a square that only covers a fifth of a turn.

    The caller is responsible for having brought the point into that square and
    for putting the answer back in the right part of the turn. This is the
    lookup and nothing else.
    """
    return ARCTAN[(across & (ARCTAN_SIDE - 1)) * ARCTAN_SIDE + (down & (ARCTAN_SIDE - 1))]
